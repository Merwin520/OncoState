"""Write DATA_AUDIT.md from the audited manifests and official sources (all numbers computed here, none typed in)."""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from ingestion.clinical_loader import ispy1_clinical, ispy2_clinical, ispy2_measurements  # noqa: E402
from ingestion.metadata_loader import load_series  # noqa: E402
from paths import EXPORTS, PKG, config  # noqa: E402

TP = ['T0', 'T1', 'T2', 'T3']


def main():
    vm = pd.read_csv(EXPORTS / 'ispy2_visit_manifest.csv', dtype={'patient_id': str})
    pm = pd.read_csv(EXPORTS / 'ispy2_patient_manifest.csv', dtype={'patient_id': str})
    flow = pd.read_csv(EXPORTS / 'cohort_flow.csv')
    src = json.loads((EXPORTS / 'audit_sources.json').read_text())
    clin, _ = ispy2_clinical()
    meas, _ = ispy2_measurements()
    s1, _ = load_series('ispy1')
    c1, c1src = ispy1_clinical()
    img = set(pm.patient_id)

    # official FTV (SEG header) vs UCSF multi-feature table
    agree = []
    for v, t in zip(['V10', 'V20', 'V30', 'V40'], TP):
        j = vm[vm.timepoint == t].merge(meas[['patient_id', f'VOLUME_TUM_BLU_{v}']], on='patient_id')
        d = (j.ftv_pe_cc_official - j[f'VOLUME_TUM_BLU_{v}']).abs()
        agree.append(dict(timepoint=t, n=len(j), identical_lt_0p01cc=int((d < .01).sum()), pct_identical=round(100 * (d < .01).mean(), 1),
                          median_abs_diff_cc=round(d.median(), 3), max_abs_diff_cc=round(d.max(), 2),
                          spearman=round(spearmanr(j.ftv_pe_cc_official, j[f'VOLUME_TUM_BLU_{v}']).statistic, 4)))
    agree = pd.DataFrame(agree)
    tp_counts = vm.groupby('timepoint').agg(studies=('study_uid', 'size'), patients=('patient_id', 'nunique'),
                                            FTV_official=('ftv_pe_cc_official', lambda x: int(x.notna().sum())), FTV_zero=('ftv_pe_cc_official', lambda x: int((x == 0).sum())),
                                            FTV_median_cc=('ftv_pe_cc_official', 'median'), mask_SEG=('has_FTV_mask', 'sum'), cropped_DCE=('has_cropped_DCE', 'sum'),
                                            PE_map=('has_PE_map', 'sum'), SER_map=('has_SER_map', 'sum')).round(2).reset_index()
    flags = vm.QC_flags.fillna('').str.split(';').explode().replace('', np.nan).dropna().value_counts()
    pe_lab = vm.ftv_label.value_counts()
    pat = pm.visit_pattern.value_counts().rename_axis('visit pattern (digit = valid visit, - = absent)').reset_index(name='patients')
    clin_img = clin[clin.patient_id.isin(img)]
    ld1 = {k: int(c1[k].notna().sum()) for k in config('ispy1_optional')['visit_map']}
    i1_pattern = c1[list(ld1)].notna().apply(lambda r: ''.join(str(i) if x else '-' for i, x in enumerate(r)), axis=1).value_counts()

    L = ['# Experiment 2.8 — Data audit (I-SPY2 Imaging Cohort 1; I-SPY1 for optional replication)', '',
         f"Generated by `scripts/data_audit.py` from `exports/` (manifests built by `scripts/prepare_ispy2.py --metadata-only`). "
         f"No imaging pixels were read. IDC data version **{src['idc'].get('idc_version')}**, collection `ispy2`, DOI {config('ispy2')['source_doi']}.", '',
         '## 1. Sources', '',
         '| Source | Content | SHA-256 |', '|---|---|---|',
         f"| IDC index (`idc-index`) | {s1.shape[0] and len(load_series('ispy2')[0])} I-SPY2 series metadata | — |",
         f"| `{src['clinical']['file']}` | clinical, {len(clin)} rows (sheet `{src['clinical']['sheet']}`) | `{src['clinical']['sha256'][:16]}…` |",
         f"| `{src['measurements']['file']}` | UCSF multi-feature MRI table, {len(meas)} rows (sheet `{src['measurements']['sheet']}`) | `{src['measurements']['sha256'][:16]}…` |",
         f"| analysis-mask SEG headers ({src['n_seg_headers']}) | official UCSF FTV in private tags (0117,10B0–10B5) | per-object URL in `ispy2_visit_manifest.csv` source |",
         f"| `{c1src['file']}` (I-SPY1) | clinical + outcome subsets, {len(c1)} patients | `{c1src['sha256'][:16]}…` |", '',
         '## 2. Cohort (actual counts)', '', flow.to_markdown(index=False), '',
         f"All {len(img)} imaging patients have a clinical record ({len(clin)} rows in the clinical file: the imaging cohort is a subset). "
         'A visit is *valid* when it has an unambiguous T0–T3 label, a single study for that label, consistent patient ID and time ordering, '
         'and an official FTV. No study failed these checks.', '',
         '## 3. Visit completeness', '', tp_counts.to_markdown(index=False), '', pat.to_markdown(index=False), '',
         '- Timepoints come from `StudyDescription` (`ISPY2_MRI_T0…T3`) and agree with the DICOM ClinicalTrialTimePointID tag in the SEG header for every study.',
         '- Study dates are increasing T0 < T1 < T2 < T3 for every patient.',
         '- Natural missingness exists: intermediate visits are absent in '
         f"{int(pm.visit_pattern.isin(['01-3', '0-23', '0--3', '0-2-']).sum())} patients, trailing visits in "
         f"{int(pm.visit_pattern.isin(['012-', '01--', '0---']).sum())}, and T0 is absent in {int(pm.visit_pattern.str.startswith('-').sum())}.", '',
         '## 4. Available measurements', '',
         f"**Official FTV (all visits).** Every SEG header carries two UCSF results: FTVpe (PE-thresholded functional tumour volume, cc) and FTVser "
         f"(additionally SER > 0.9). Present for {int(vm.ftv_pe_cc_official.notna().sum())}/{len(vm)} studies. PE threshold label: "
         + ', '.join(f'{k} {v}' for k, v in pe_lab.items()) + '. Studies not at the standard 70 % threshold are flagged `nonstandard_PE_threshold` '
         '(site-specific thresholds; FTV remains the trial\'s official value, but cross-site comparability is reduced).', '',
         '**Agreement with the UCSF multi-feature table** (`VOLUME_TUM_BLU_V10…V40`, patients present in both):', '', agree.to_markdown(index=False), '',
         'The SEG-header FTVpe therefore reproduces the trial\'s published tumour-volume values; the residual differences are reported, not reconciled.', '',
         f"**Longest diameter, sphericity, BPE** exist only in the multi-feature table: {len(meas)} patients, of whom {int(meas.patient_id.isin(img).sum())} are in "
         'the imaging cohort. The sheet is named `datawith4visits` and has no missing values, i.e. it contains only patients with all four visits. '
         'LD-based trajectories are therefore available for a complete-visit subset only and cannot be used to study natural missingness.', '',
         '## 5. Masks and derived imaging objects', '',
         f"- Analysis-mask SEG: {int(vm.has_FTV_mask.sum())} studies (unilateral cropped {int((vm.mask_laterality == 'unilateral_cropped').sum())}, "
         f"bilateral {int((vm.mask_laterality == 'bilateral').sum())}). Masks are *inverse* bit-encoded masks (0 = voxel counted in FTV; "
         'bits 1 PE threshold, 2 connectivity, 8/16 background, 32 manual VOI, 64 OMIT), per the TCIA analysis-mask description.',
         f"- PE maps {int(vm.has_PE_map.sum())}, SER maps {int(vm.has_SER_map.sum())}, cropped original DCE {int(vm.has_cropped_DCE.sum())} studies "
         '(bilateral studies have an uncropped derived DCE instead).', '',
         '## 6. Treatment and outcome fields (actual columns)', '',
         f"Clinical file columns: {', '.join(c for c in clin.columns if c != 'patient_id')}.", '',
         f"- Arm ({clin_img.Arm.nunique()} arms in the imaging cohort): " + ', '.join(f'{k} {v}' for k, v in clin_img.Arm.value_counts().items()) + '.',
         f"- HR / HER2 / MP / pCR are present for all imaging patients; subtype: " + ', '.join(f'{k} {v}' for k, v in pm.clinical_subtype.value_counts().items()) + '.',
         f"- pCR: {int(clin_img.pCR.sum())} / {len(clin_img)}.",
         '- Not available: treatment start / visit-to-treatment dates, the regimen-2 (anthracycline) details, survival or follow-up beyond pCR. '
         'Treatment exposure in the state is therefore the assigned arm plus the protocol phase implied by the timepoint label.', '',
         '## 7. QC', '', '| Flag | Visits |', '|---|---|'] + [f'| {k} | {v} |' for k, v in flags.items()] + ['',
         'Per-visit QC with explicit status and reasons: `exports/qc_summary_metadata.csv`. No visit was dropped.', '',
         '## 8. I-SPY1 (optional external replication)', '',
         f"- IDC `ispy1`: {s1.PatientID.nunique()} patients, {s1.StudyInstanceUID.nunique()} studies; modalities " + ', '.join(f'{k} {v}' for k, v in s1.Modality.value_counts().items()) + '.',
         '- Study descriptions are site exam names, not visit labels; DICOM-derived visit mapping would need header reads.',
         f"- The clinical file holds MRI longest diameter at four visits with source names {', '.join(ld1)}; non-missing counts: "
         + ', '.join(f'{k} {v}' for k, v in ld1.items()) + '. Visit patterns: ' + ', '.join(f'{k} {v}' for k, v in i1_pattern.items()) + '.',
         '- These are mapped to canonical V0–V3 with the source terms kept (`configs/ispy1_optional.yaml`). No I-SPY1 volume (SER) measurement is in the shared clinical file.', '',
         '## 9. Implications for the experiment', '',
         '- **Tier 1 (state synchronization, all patients):** official FTVpe and FTVser per visit (SEG header), arm, HR/HER2, subtype, MP, '
         'with provenance to the SEG series UID and the clinical file. LD/sphericity/BPE added where the multi-feature table has them.',
         '- **Reference for trajectory fidelity:** the source observations themselves (SEG-header FTV, table LD); the state must reproduce them exactly '
         'at every version. The multi-feature table is an independent second reference for 283 patients.',
         '- **Missingness:** natural missing visits exist (section 3), so missingness fidelity is tested on real absences, separately from the '
         'artificial missing-visit stress test.',
         '- **Tier 2 (imaging-grounded):** recompute FTV locally from the analysis mask and early PE map for a small streamed subset and compare with the '
         'official value. A locally recomputed value is labelled `local_ftv_recomputed`, never "official FTV".']
    (PKG / 'DATA_AUDIT.md').write_text('\n'.join(L) + '\n')
    agree.to_csv(EXPORTS / 'ftv_header_vs_table_agreement.csv', index=False)
    print('\n'.join(L[:40]))


if __name__ == '__main__':
    main()
